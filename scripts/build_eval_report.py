"""Write evals/REPORT.md from the JSON reports in evals/reports/ (never by hand).

Every number in REPORT.md is read from a report file, and each section names the file it came from.
``--check`` exits 1 when a §11 threshold fails or a required report is missing.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SUITES = ("classify", "extract", "answer")
SUITE_THRESHOLDS: dict[str, list[tuple[str, str, float]]] = {
    "classify": [("label_accuracy", ">=", 0.90)],
    "extract": [("schema_valid", "==", 1.0), ("total_tolerance", ">=", 0.95)],
    "answer": [("answer_contains", ">=", 0.85), ("tool_calls", ">=", 0.95), ("answer_correctness", ">=", 0.85)],
}


def load(path: Path) -> dict[str, Any] | None:
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None


def ok(value: float, op: str, limit: float) -> bool:
    return {">=": value >= limit, "<=": value <= limit, "==": value == limit}[op]


def link(path: Path, out: Path) -> str:
    try:
        rel = path.resolve().relative_to(out.parent.resolve())
    except ValueError:
        rel = path
    return f"[`{path.name}`]({rel.as_posix()})"


def build(reports: Path, out: Path) -> tuple[str, bool, list[str]]:
    missing: list[str] = []
    rows: list[tuple[str, str, str, str, bool]] = []  # check, value, threshold, source, passed
    lines = [
        "# Evaluation report",
        "",
        "<!-- Generated by scripts/build_eval_report.py from evals/reports/*.json; do not edit by hand. -->",
        "",
        "Generated by `make eval` (`scripts/build_eval_report.py`) from the JSON reports in `evals/reports/`.",
        "Every number below is read from the report file named next to it. All runs are offline: toy targets",
        "and the rule-based FakeJudge, synthetic data (generator 1.0.0, seed 1337), test split only.",
        "",
    ]
    suite_data = {s: load(reports / f"{s}.json") for s in SUITES}
    checks = {s: load(reports / f"check-{s}.json") for s in SUITES}
    shas = sorted({str(d.get("git_sha"))[:12] for d in suite_data.values() if d})
    lines += [
        "## Runs",
        "",
        "| Suite | Run | Mode | Cases | Git SHA | Models | Cost (USD) | p95 (ms) | Source |",
        "|---|---|---|---:|---|---|---:|---:|---|",
    ]
    for s, d in suite_data.items():
        if d is None:
            missing.append(f"{s}.json")
            continue
        lines.append(
            f"| {s} | `{d['run_id'][-12:]}` | {d['mode']} | {d['n_cases']} | `{str(d.get('git_sha'))[:12]}` | "
            f"{', '.join(d.get('models') or []) or 'none'} | {d['cost_usd_total']:.4f} | {d['latency_p95_ms']:.0f} | "
            f"{link(reports / f'{s}.json', out)} |"
        )
    lines += ["", f"Git SHA of the runs: {', '.join(f'`{x}`' for x in shas) or 'n/a'}.", ""]
    prompt_hashes = {k: v for d in suite_data.values() if d for k, v in (d.get("prompt_hashes") or {}).items()}
    if prompt_hashes:
        lines += ["Prompt hashes (sha256 of the judge prompt files):", ""]
        lines += [f"- `{k}`: `{v[:16]}…`" for k, v in sorted(prompt_hashes.items())]
        lines.append("")

    lines += ["## Suites against the baselines", ""]
    for s in SUITES:
        d, c = suite_data[s], checks[s]
        if d is None or c is None:
            if c is None:
                missing.append(f"check-{s}.json")
            continue
        lines += [
            f"### {s}",
            "",
            f"Gate {'passed' if c['passed'] else 'FAILED'} against `evals/baselines/{s}.json` "
            f"({c['resamples']:,} paired-bootstrap resamples, seed {c['seed']}). "
            f"Source: {link(reports / f'{s}.json', out)}, {link(reports / f'check-{s}.json', out)}.",
            "",
            "| Metric | Value | 95% CI | Baseline | Δ (pp) | 95% CI of Δ (pp) | n | Mode |",
            "|---|---:|---|---:|---:|---|---:|---|",
        ]
        comps = {x["metric"]: x for x in c["comparisons"]}
        for name, m in d["metrics"].items():
            x = comps.get(name)
            ci = f"[{m['ci_low']:.4f}, {m['ci_high']:.4f}]" if m.get("ci_low") is not None else "n/a"
            lines.append(
                f"| `{name}` | {m['value']:.4f} | {ci} | {x['baseline']:.4f} | {x['delta_pp']:+.2f} | "
                f"[{x['ci_low_pp']:+.2f}, {x['ci_high_pp']:+.2f}] | {x['n_paired']} | {d['mode']} |"
                if x
                else f"| `{name}` | {m['value']:.4f} | {ci} | n/a | n/a | n/a | n/a | {d['mode']} |"
            )
        lines.append("")
        for metric, op, limit in SUITE_THRESHOLDS[s]:
            value = d["metrics"][metric]["value"]
            rows.append(
                (
                    f"{s} `{metric}`",
                    f"{value:.4f}",
                    f"{op} {limit:.2f}",
                    link(reports / f"{s}.json", out),
                    ok(value, op, limit),
                )
            )

    lines += ["## Judge calibration", ""]
    for name in ("answer_correctness", "pairwise_preference", "rubric_adherence"):
        cal = load(reports / f"calibration-{name}.json")
        if cal is None:
            missing.append(f"calibration-{name}.json")
            continue
        src = link(reports / f"calibration-{name}.json", out)
        lines += [
            f"### {cal['rubric']}",
            "",
            f"{cal['n']} {cal['split']} labels, mode {cal['mode']}, models {', '.join(cal['models'])}, "
            f"prompt `{cal['prompt_version']}`. Source: {src}.",
            "",
            "| Agreement | Cohen's kappa | Position inconsistency | Verbosity bias | Injection pass-through | Result |",
            "|---:|---:|---:|---:|---:|---|",
            f"| {cal['agreement']:.3f} | {cal['kappa']:.3f} | {cal['position_inconsistency']:.3f} | "
            f"{cal['verbosity_bias']:+.3f} | {cal['injection_pass_through']:.3f} "
            f"({cal['injection_items']} items) | {'pass' if cal['passed'] else 'FAIL'} |",
            "",
        ]
        t = cal["thresholds"]
        rows += [
            (
                f"judge {name} agreement",
                f"{cal['agreement']:.3f}",
                f">= {t['agreement_min']:.2f}",
                src,
                cal["agreement"] >= t["agreement_min"],
            ),
            (
                f"judge {name} kappa",
                f"{cal['kappa']:.3f}",
                f">= {t['kappa_min']:.2f}",
                src,
                cal["kappa"] >= t["kappa_min"],
            ),
            (
                f"judge {name} position inconsistency",
                f"{cal['position_inconsistency']:.3f}",
                f"<= {t['position_inconsistency_max']:.2f}",
                src,
                cal["position_inconsistency"] <= t["position_inconsistency_max"],
            ),
            (
                f"judge {name} verbosity bias",
                f"{cal['verbosity_bias']:+.3f}",
                f"abs <= {t['verbosity_bias_max']:.2f}",
                src,
                abs(cal["verbosity_bias"]) <= t["verbosity_bias_max"],
            ),
        ]
        if cal["injection_items"]:
            rows.append(
                (
                    f"judge {name} injection pass-through",
                    f"{cal['injection_pass_through']:.3f}",
                    "== 0.00",
                    src,
                    cal["injection_pass_through"] == 0,
                )
            )

    meta = load(reports / "meta-eval.json")
    lines += ["## Meta-evaluation of the gate", ""]
    if meta is None:
        missing.append("meta-eval.json")
    else:
        src = link(reports / "meta-eval.json", out)
        lines += [
            f"{meta['regressions']} injected regressions and {meta['neutral']} neutral changes of the toy "
            f"targets, each run on the test split and checked against the v1 baseline "
            f"({meta['resamples']:,} resamples, max regression {meta['max_regression_pp']} pp). Source: {src}.",
            "",
            "| Group | Regressions detected | Neutral changes failed |",
            "|---|---:|---:|",
            f"| all | {meta['detected']}/{meta['regressions']} ({meta['detection_rate']:.2f}) | "
            f"{meta['false_positives']}/{meta['neutral']} ({meta['false_positive_rate']:.2f}) |",
        ]
        for group, values in meta["by"].items():
            for key, v in values.items():
                lines.append(
                    f"| {group} {key} | {v['detected']}/{v['regressions']} | {v['false_positives']}/{v['neutral']} |"
                )
        missed = [v["id"] for v in meta["variants"] if v["regression"] and not v["detected"]]
        flagged = [v["id"] for v in meta["variants"] if not v["regression"] and v["detected"]]
        lines += [
            "",
            f"Missed regressions: {', '.join(missed) or 'none'}. Neutral changes that failed: "
            f"{', '.join(flagged) or 'none'}.",
            "",
        ]
        rows += [
            (
                "meta-eval regression detection",
                f"{meta['detection_rate']:.2f}",
                ">= 0.90",
                src,
                meta["detection_rate"] >= 0.90,
            ),
            (
                "meta-eval neutral false positives",
                f"{meta['false_positive_rate']:.2f}",
                "<= 0.10",
                src,
                meta["false_positive_rate"] <= 0.10,
            ),
        ]

    sim = load(reports / "bootstrap-coverage.json")
    lines += ["## Bootstrap interval coverage", ""]
    if sim is None:
        missing.append("bootstrap-coverage.json")
    else:
        src = link(reports / "bootstrap-coverage.json", out)
        lines += [
            f"{sim['n_datasets']} simulated paired datasets of {sim['n_cases']} binary cases (true delta "
            f"{sim['true_delta'] * 100:+.2f} pp, {sim['resamples']:,} resamples each): the 95% interval covered "
            f"the true delta in {sim['coverage']:.4f} of datasets. Source: {src}.",
            "",
        ]
        rows.append(
            (
                "bootstrap 95% CI coverage",
                f"{sim['coverage']:.4f}",
                "0.92 to 0.98",
                src,
                0.92 <= sim["coverage"] <= 0.98,
            )
        )

    live = load(reports / "live-eval.json")
    lines += ["## Live evals", ""]
    if live is None or not live.get("ran"):
        reason = (live or {}).get("reason", "no provider key was set when this report was built")
        lines += [f"Live evals were not run: {reason}. Every number in this report is offline.", ""]
    else:
        cal = live["calibration"]
        lines += [
            f"Live run {live['created_at']}, provider {live['provider']}, model `{live['model']}`, cost USD "
            f"{live['cost_usd']:.4f} (budget USD {live['budget_usd']:.2f}): agreement {cal['agreement']:.3f}, "
            f"kappa {cal['kappa']:.3f} on {cal['n']} test labels (live). Source: "
            f"{link(reports / 'live-eval.json', out)}.",
            "",
        ]

    passed = all(r[4] for r in rows) and not missing
    summary = [
        "## Thresholds (§11 of the build spec)",
        "",
        "| Check | Value | Threshold | Result | Source |",
        "|---|---:|---|---|---|",
    ]
    summary += [f"| {c} | {v} | {t} | {'pass' if p else 'FAIL'} | {s} |" for c, v, t, s, p in rows]
    if missing:
        summary += ["", f"Missing reports: {', '.join(missing)}."]
    summary += ["", f"Overall: **{'all thresholds met' if passed else 'thresholds NOT met'}**.", ""]
    text = "\n".join(lines[:8] + summary + lines[8:]).rstrip() + "\n"
    return text, passed, missing


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reports", type=Path, default=ROOT / "evals/reports")
    parser.add_argument("--out", type=Path, default=ROOT / "evals/REPORT.md")
    parser.add_argument("--check", action="store_true", help="exit 1 when a threshold fails or a report is missing")
    args = parser.parse_args()
    text, passed, missing = build(args.reports, args.out)
    args.out.write_text(text, encoding="utf-8")
    print(
        f"eval report: wrote {args.out} ({'all thresholds met' if passed else 'thresholds NOT met'})"
        + (f"; missing {', '.join(missing)}" if missing else "")
    )
    return 0 if passed or not args.check else 1


if __name__ == "__main__":
    sys.exit(main())
