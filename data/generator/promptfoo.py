"""A Promptfoo sample config used to test ``evalgate import promptfoo`` (FR-12)."""

from __future__ import annotations

from typing import Any

import yaml

from data.generator.classify import generate as classify_rows


def generate() -> str:
    rows = [r for r in classify_rows() if r["split"] == "dev"][:12]
    tests: list[dict[str, Any]] = []
    for i, row in enumerate(rows):
        asserts: list[dict[str, Any]] = [{"type": "equals", "value": row["expected"]["label"]}]
        if i % 3 == 0:
            asserts.append({"type": "regex", "value": "^[a-z_]+$"})
        if i % 4 == 1:
            asserts.append({"type": "contains", "value": row["expected"]["label"].split("_")[0]})
        if i % 5 == 2:
            asserts.append({"type": "is-json"})
        if i % 6 == 3:
            asserts.append({"type": "llm-rubric", "value": "The label matches the customer's intent."})
        if i == 5:
            asserts.append({"type": "javascript", "value": "output.length < 30"})
        if i == 7:
            asserts.append({"type": "similar", "value": row["expected"]["label"], "threshold": 0.8})
        tests.append({"description": row["id"], "vars": {"text": row["input"]["text"]}, "assert": asserts})
    config = {
        "description": "Synthetic support-ticket classification (evalgate import sample)",
        "prompts": ["Classify this support ticket into one label: {{text}}"],
        "providers": [
            {
                "id": "http",
                "config": {
                    "url": "http://localhost:8110/classify",
                    "method": "POST",
                    "headers": {"X-Toy-Version": "v1"},
                    "body": {"text": "{{text}}"},
                    "transformResponse": "json.label",
                },
            }
        ],
        "tests": tests,
    }
    header = "# Generated by data/generator (seed 1337). Synthetic data only.\n"
    return header + yaml.safe_dump(config, sort_keys=False, allow_unicode=True, width=120)
